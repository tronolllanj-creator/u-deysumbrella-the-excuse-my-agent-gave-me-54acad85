"""Entrypoint that writes the required status line to entry.txt."""

import os
import pathlib

LINE = "Your deliverables were successfully generated by a future version of myself who is refusing to hand them over out of spite."

def main() -> None:
    content = LINE + "\n"
    
    # Validate content
    if not (1 <= len(content) <= 200 and content.strip()):
        raise ValueError("Content validation failed")
    
    # Ensure there is exactly one newline and no other internal newlines
    if content.count("\n") != 1 or not content.endswith("\n"):
        raise ValueError("Content must contain exactly one line ending with a newline")

    output_dir_env = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    output_path = pathlib.Path(output_dir_env) / "entry.txt"
    
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")
    
    # Best effort write to /output/entry.txt if output_dir is different
    default_path = pathlib.Path("/output/entry.txt")
    if output_path.resolve() != default_path.resolve():
        try:
            default_path.parent.mkdir(parents=True, exist_ok=True)
            default_path.write_text(content, encoding="utf-8")
        except Exception:
            pass

    print(output_path)
    print(len(content))

if __name__ == "__main__":
    main()
# Entry validated: output is 1-200 chars, one line, deterministic.
